// レンダラーに安全な API だけを公開する
const { contextBridge, ipcRenderer } = require('electron');

async function call(channel, arg) {
  const r = await ipcRenderer.invoke(channel, arg);
  if (!r.ok) throw new Error(r.error);
  return r.data;
}

